def table():
    """给前端用的整份表：{lang: {key: text}}"""
    return T


def pick(accept_language: str):
    """从 Accept-Language 里挑一个我们支持的语言。"""
    if not accept_language:
        return DEFAULT_LANG
    for part in accept_language.split(","):
        tag = part.split(";")[0].strip().lower()
        if not tag:
            continue
        if tag in T:
            return tag
        short = tag.split("-")[0]
        for lang in T:
            if lang.split("-")[0] == short:
                return lang
    return "en"
